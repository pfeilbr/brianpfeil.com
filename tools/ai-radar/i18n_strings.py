def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def block(lang):
    n = LANGS.index(lang)
    out = [BEGIN]
    for k, vals in S.items():
        out += ["", "[%s]" % k, "other = %s" % toml_str(vals[n])]
    out.append(END)
    return "\n".join(out) + "\n"


def apply(text, lang):
    b = block(lang)
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        return head + b + (("\n" + tail) if tail else "")
    return text.rstrip("\n") + "\n\n" + b


def main(argv):
    for vals in S.values():
        assert len(vals) == len(LANGS) and all(v.strip() for v in vals), vals[0]
    stale = []
    for lang in LANGS:
        p = ROOT / "i18n" / ("%s.toml" % lang)
        old = p.read_text()
        new = apply(old, lang)
        if new != old:
            stale.append(p.name)
            if "--check" not in argv:
                p.write_text(new)
    if "--check" in argv and stale:
        print("stale /ai/ strings in:", ", ".join(stale), "-- run tools/ai-radar/i18n_strings.py")
        return 1
    print(("updated " + ", ".join(stale)) if stale else "i18n up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
